  await page.evaluate(()=>{window.fetch=window.auditOriginalFetch;});
  checks.push('停止AI请求后输入恢复可用，可以继续本地检索');
  await page.evaluate(()=>{window.fetch=(url,options)=>String(url).endsWith('api/ask')?Promise.reject(new Error('simulate offline')):window.auditOriginalFetch(url,options);});
  await page.select('#ai-chat-answer-mode','auto');await page.type('#ai-chat-question','遵义会议');await page.click('#ai-chat [data-role="send"]');
  await page.waitForFunction(()=>document.querySelector('#ai-chat [data-role="status"]').textContent.includes('暂不可用'));
