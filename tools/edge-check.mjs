  checks.push('首页不会因收藏格式损坏丢掉有效阅读进度');
  await page.evaluate(()=>localStorage.setItem('shanhe-jisi-v1',JSON.stringify({bookmarks:[],message:'old message',name:'reader',created:'',extra:'keep field'})));
  await page.goto(base+'long-scroll.html',{waitUntil:'networkidle0'});
  const second=await browser.newPage();await second.goto(base,{waitUntil:'networkidle0'});
  await second.evaluate(()=>{const state=JSON.parse(localStorage.getItem('shanhe-jisi-v1'));state.message='new message';localStorage.setItem('shanhe-jisi-v1',JSON.stringify(state));});
  await page.bringToFront();await page.click('#bookmark');
  saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('shanhe-jisi-v1')));
  assert.equal(saved.message,'new message');assert.equal(saved.extra,'keep field');
  await second.evaluate(()=>{const state=JSON.parse(localStorage.getItem('shanhe-jisi-v1'));state.bookmarks.push('1972');localStorage.setItem('shanhe-jisi-v1',JSON.stringify(state));});
  await page.$eval('#memory-message',el=>el.value='message from this form');
