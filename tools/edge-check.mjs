  assert.deepEqual(saved.state.bookmarks,['1935','1921']);assert.equal(saved.state.message,'keep message');assert.deepEqual(saved.read,['1921']);
  checks.push('阅读JSON损坏时仍可收藏，原寄语与已有收藏保留');
  await page.evaluate(()=>{localStorage.setItem('shanhe-jisi-v1','{');localStorage.setItem('shanhe-reading-v1','["1935"]');});
